/// 返回动作标识对应的中文描述；未知动作回退为动作标识本身。
pub fn action_description(action: &str) -> &str {
    ACTION_DESCRIPTIONS
        .binary_search_by_key(&action, |&(a, _)| a)
        .map(|i| ACTION_DESCRIPTIONS[i].1)
        .unwrap_or(action)
}
